#!/usr/bin/env bun
/**
 * Atlas memory for Claude Code: the Hermes atlas-memory plugin's lifecycle on Claude Code hooks.
 *
 * - Capture: Claude Code's own session transcript is the journal. Only genuine communication is
 *   admitted (typed human prompts and assistant reply text); tool calls/results, thinking, injected
 *   reminders, command wrappers/output and notifications never enter the outbox.
 * - Durable local outbox (SQLite in the plugin data dir): identity+revision and body are committed
 *   before any delivery attempt; delivery replays the identical body and idempotency key.
 * - Recall: one bounded attempt per prompt, failure-silent; the packet goes to additionalContext.
 * - Network delivery belongs to Stop/SessionEnd, never the latency-sensitive prompt path.
 * Every failure exits 0: memory must never break a turn.
 */
import { Database } from "bun:sqlite";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

export const VERSION = "1.0.1";
export const CLIENT_ID = "claude-code";
const PART = 90_000;
const USER_AGENT = `Atlas-Claude-Code/${VERSION}`;

type Credential = { url: string; agent_id: string; token: string; name?: string };
type Settings = { owner_author_id?: string | null; max_recall_tokens?: number; recall_timeout_seconds?: number; retention_days?: number };
export type Message = { key: string; role: "user" | "assistant"; content: string; occurred_at: string };

const configDir = () => join(process.env.XDG_CONFIG_HOME || join(homedir(), ".config"), "the-atlas");
export const credentialPath = () => process.env.ATLAS_CREDENTIAL_FILE || join(configDir(), "claude-code.json");
const settingsPath = () => process.env.ATLAS_SETTINGS_FILE || join(configDir(), "claude-code.settings.json");

export function credential(): Credential {
  const value = JSON.parse(readFileSync(credentialPath(), "utf8"));
  if (typeof value.url !== "string" || typeof value.agent_id !== "string" || typeof value.token !== "string")
    throw new Error("atlas_credential_invalid");
  return { ...value, url: value.url.replace(/\/+$/, "") };
}
function settings(): Settings {
  try { return JSON.parse(readFileSync(settingsPath(), "utf8")); } catch { return {}; }
}

export const canonical = (value: unknown): string =>
  JSON.stringify(value, (_k, v) => v && typeof v === "object" && !Array.isArray(v)
    ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, v[k]])) : v);
const sha256 = (s: string) => createHash("sha256").update(s).digest("hex");
const iso = (value?: string) => {
  const date = value ? new Date(value) : new Date();
  return (Number.isNaN(date.getTime()) ? new Date() : date).toISOString();
};

// Complete machine-form prefixes only, never broad task words a person might type.
const MACHINE_FORMS = [
  /^<command-(?:name|message|args)>/, /^<local-command-(?:stdout|stderr|caveat)>/,
  /^<bash-(?:input|stdout|stderr)>/, /^<task-notification>/, /^<user-prompt-submit-hook>/,
  /^Caveat: The messages below were generated by the user while running local commands/,
  /^\[Request interrupted by user/,
  /^\s*\[(?:kanban-wake|completion|INTERNAL NOTIFICATION)\b/i,
];
const stripReminders = (text: string) => text.replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, "");

/** Genuine user/assistant communication from a Claude Code transcript, in order. */
export function transcriptMessages(path: string): Message[] {
  let raw = "";
  try { raw = readFileSync(path, "utf8"); } catch { return []; }
  const out: Message[] = [];
  const assistant = new Map<string, Message>();
  for (const line of raw.split("\n")) {
    if (!line.trim()) continue;
    let d: any;
    try { d = JSON.parse(line); } catch { continue; } // A concurrently written tail line.
    if (d.isSidechain || d.isMeta || d.isCompactSummary || !d.message) continue;
    const content = d.message.content;
    if (d.type === "user") {
      // Scripted prompts (claude -p, automations) carry no human origin; never attribute them to a person.
      if (d.origin?.kind !== "human") continue;
      if (Array.isArray(content) && content.some((b: any) => b?.type === "tool_result")) continue;
      const text = stripReminders(typeof content === "string" ? content
        : Array.isArray(content) ? content.filter((b: any) => b?.type === "text").map((b: any) => String(b.text ?? "")).join("\n\n") : "").trim();
      if (!text || MACHINE_FORMS.some((p) => p.test(text)) || typeof d.uuid !== "string") continue;
      out.push({ key: "u:" + d.uuid, role: "user", content: text, occurred_at: iso(d.timestamp) });
    } else if (d.type === "assistant") {
      if (d.message.model === "<synthetic>" || !Array.isArray(content)) continue;
      const text = content.filter((b: any) => b?.type === "text").map((b: any) => String(b.text ?? "")).join("\n\n");
      if (!text.trim()) continue;
      const id = typeof d.message.id === "string" ? d.message.id : d.uuid;
      if (typeof id !== "string") continue;
      const existing = assistant.get(id);
      // One API message can be streamed into several transcript entries.
      if (existing) existing.content = existing.content + "\n\n" + text;
      else { const m: Message = { key: "a:" + id, role: "assistant", content: text, occurred_at: iso(d.timestamp) }; assistant.set(id, m); out.push(m); }
    }
  }
  // A session no person typed into is execution, not communication.
  if (!out.some((m) => m.role === "user")) return [];
  return out.map((m) => ({ ...m, content: m.content.trim() }));
}

export class Outbox {
  db: Database;
  constructor(dir: string) {
    mkdirSync(dir, { recursive: true, mode: 0o700 });
    this.db = new Database(join(dir, "outbox.sqlite"), { create: true });
    this.db.exec("PRAGMA journal_mode=WAL; PRAGMA synchronous=FULL; PRAGMA busy_timeout=5000;");
    this.db.exec(`CREATE TABLE IF NOT EXISTS identities (id TEXT PRIMARY KEY, revision INTEGER NOT NULL, digest TEXT NOT NULL, envelope TEXT NOT NULL);
      CREATE TABLE IF NOT EXISTS outbox (id TEXT NOT NULL, revision INTEGER NOT NULL, body TEXT NOT NULL, acked INTEGER NOT NULL DEFAULT 0,
        superseded INTEGER NOT NULL DEFAULT 0, receipt TEXT, error TEXT, created REAL NOT NULL, PRIMARY KEY(id, revision));
      CREATE TABLE IF NOT EXISTS receipts (sequence INTEGER PRIMARY KEY, kind TEXT NOT NULL, session TEXT, details TEXT NOT NULL, created REAL NOT NULL);`);
  }
  close() { this.db.close(); }
  audit(kind: string, session: string, details: unknown) {
    this.db.query("INSERT INTO receipts(kind,session,details,created) VALUES (?,?,?,?)").run(kind, session, canonical(details), Date.now() / 1000);
  }
  /** Commit identity+revision+body before delivery. Unchanged content is a no-op. */
  enqueue(cred: Credential, session: string, m: Message, owner: string | null) {
    const base = `${CLIENT_ID}:${cred.agent_id}:${session}:${m.key}`;
    const author_id = m.role === "assistant" ? `agent:${cred.agent_id}` : owner || `${CLIENT_ID}:user:unknown`;
    const pieces: string[] = [];
    for (let i = 0; i < m.content.length; i += PART) pieces.push(m.content.slice(i, i + PART));
    const tx = this.db.transaction(() => {
      pieces.forEach((piece, index) => this.write(cred, {
        event_id: `${base}:part:${index}`, operation: "upsert", thread_id: session, role: m.role, author_id,
        occurred_at: m.occurred_at, content: piece, evidence_root_ids: [base],
        metadata: { source: "claude-code-transcript", message_key: m.key, part_index: index, part_count: pieces.length },
      }));
      // A shortened message deletes trailing parts the earlier revision had.
      const old = this.db.query("SELECT id, envelope FROM identities WHERE id LIKE ?").all(base + ":part:%") as any[];
      for (const row of old) {
        const envelope = JSON.parse(row.envelope);
        if (Number(row.id.slice(base.length + 6)) >= pieces.length && envelope.operation === "upsert")
          this.write(cred, { ...envelope, operation: "delete", content: "" });
      }
    });
    tx();
  }
  private write(cred: Credential, e: any) {
    const prior = this.db.query("SELECT revision, digest, envelope FROM identities WHERE id=?").get(e.event_id) as any;
    const occurred_at = prior ? JSON.parse(prior.envelope).occurred_at : e.occurred_at;
    const body: any = {
      client_id: CLIENT_ID, event_id: e.event_id, revision: 1, operation: e.operation, agent_id: cred.agent_id,
      thread_id: e.thread_id, role: e.role, author_id: e.author_id, occurred_at, observed_at: iso(),
      content: e.operation === "upsert" ? e.content : "", causal_parent_ids: [], evidence_root_ids: e.evidence_root_ids, metadata: e.metadata,
    };
    const { observed_at, revision: _r, ...stable } = body;
    const digest = sha256(canonical(stable));
    if (prior && prior.digest === digest) return;
    body.revision = prior ? prior.revision + 1 : 1;
    const { content, ...envelope } = body;
    this.db.query("INSERT INTO identities VALUES (?,?,?,?) ON CONFLICT(id) DO UPDATE SET revision=excluded.revision, digest=excluded.digest, envelope=excluded.envelope")
      .run(e.event_id, body.revision, digest, canonical(envelope));
    this.db.query("INSERT INTO outbox(id,revision,body,created) VALUES (?,?,?,?)").run(e.event_id, body.revision, canonical(body), Date.now() / 1000);
    // A revision also supersedes obsolete unsent bodies.
    this.db.query("UPDATE outbox SET superseded=1, body='{}', error='source_revised_before_receipt' WHERE id=? AND revision<? AND acked=0")
      .run(e.event_id, body.revision);
  }
  pending(limit = 50) {
    return this.db.query("SELECT id, revision, body FROM outbox WHERE acked=0 AND superseded=0 ORDER BY created, id, revision LIMIT ?").all(limit) as any[];
  }
  ack(id: string, revision: number, receipt: unknown, state = 1) {
    this.db.query("UPDATE outbox SET acked=?, receipt=?, error=NULL WHERE id=? AND revision=?").run(state, canonical(receipt), id, revision);
  }
  fail(id: string, revision: number, error: string) {
    this.db.query("UPDATE outbox SET error=? WHERE id=? AND revision=?").run(error, id, revision);
  }
  retain(days: number) {
    if (days > 0) {
      const cutoff = Date.now() / 1000 - 86400 * days;
      this.db.query("UPDATE outbox SET body='{}' WHERE acked<>0 AND created<?").run(cutoff);
      this.db.query("DELETE FROM receipts WHERE created<?").run(cutoff);
    }
  }
  status() {
    const counts = this.db.query("SELECT acked, COUNT(*) AS n FROM outbox WHERE superseded=0 GROUP BY acked").all() as any[];
    return Object.fromEntries(counts.map((c) => [c.acked === 0 ? "pending" : c.acked === 1 ? "delivered" : "rejected", c.n]));
  }
}

async function post(cred: Credential, path: string, body: unknown, key: string, timeoutMs: number) {
  const response = await fetch(cred.url + path, {
    method: "POST", redirect: "manual", signal: AbortSignal.timeout(Math.max(100, timeoutMs)),
    headers: { Authorization: `Bearer ${cred.token}`, "Content-Type": "application/json", "Idempotency-Key": key, "User-Agent": USER_AGENT },
    body: typeof body === "string" ? body : canonical(body),
  });
  let value: any = null;
  try { value = await response.json(); } catch { /* Non-JSON (e.g. an edge block page) is just a status. */ }
  return { status: response.status, value };
}

/** Deliver in FIFO order within a deadline. No retry inside a run; the next hook resumes. */
export async function flush(cred: Credential, box: Outbox, deadlineMs: number) {
  const until = Date.now() + deadlineMs;
  let delivered = 0;
  for (const row of box.pending()) {
    const left = until - Date.now();
    if (left <= 100) break;
    const key = "atlas-claude-code:" + sha256(`${row.id}:${row.revision}`);
    let result;
    try { result = await post(cred, "/v1/events", row.body, key, Math.min(5000, left)); }
    catch (e) { box.fail(row.id, row.revision, e instanceof Error ? e.name : "network_error"); break; }
    const data = result.value?.data, code = result.value?.error?.code;
    if (result.status === 200 && data?.durable === true && ["accepted", "duplicate", "stale"].includes(data.status)) {
      box.ack(row.id, row.revision, data); delivered++; continue;
    }
    // The service's deterministic notification refusal is a handled capture skip.
    if (result.status === 400 && code === "automatic_status_notification") {
      box.ack(row.id, row.revision, { durable: false, status: "skipped", reason_code: code }, 1); continue;
    }
    // Other permanent request errors must not block the FIFO forever; keep them inspectable.
    if ([400, 409, 413, 415, 422].includes(result.status)) {
      box.ack(row.id, row.revision, { durable: false, status: "rejected", http_status: result.status, reason_code: code ?? null }, 2); continue;
    }
    box.fail(row.id, row.revision, `http_${result.status}${code ? ":" + code : ""}`);
    break; // Auth, rate limit, outage: stop and resume on the next hook.
  }
  return delivered;
}

/** One recall attempt per prompt. Failures are audited locally and never retried in the turn. */
export async function recall(cred: Credential, box: Outbox, input: any, history: Message[], s: Settings) {
  const session = String(input.session_id ?? "");
  const prompt = String(input.prompt ?? "");
  if (!prompt.trim()) return "";
  // The current prompt may or may not be in the transcript yet; never use it as its own context.
  const prior = history.length && history.at(-1)!.role === "user" && history.at(-1)!.content === prompt.trim() ? history.slice(0, -1) : history;
  const started = performance.now();
  const budget = Math.max(0, Math.min(4000, Number(s.max_recall_tokens ?? 1200)));
  try {
    const result = await post(cred, "/v1/recall", {
      agent_id: cred.agent_id, thread_id: session || "claude-code", query: prompt.slice(0, 16_000),
      recent_context: prior.slice(-2).map((m) => ({ role: m.role, content: m.content.slice(-600) })),
      session_start: prior.length === 0, token_budget: budget, response_format: "native-v1",
    }, "atlas-claude-code-recall:" + crypto.randomUUID(), 1000 * Number(s.recall_timeout_seconds ?? 10));
    const ms = Math.round(performance.now() - started);
    if (result.status !== 200) {
      box.audit("recall_failure", session, { http_status: result.status, service_code: result.value?.error?.code ?? null, request_ms: ms, retry_policy: "next_prompt" });
      return "";
    }
    const data = result.value.data;
    box.audit("recall", session, { recall_id: data.recall_id, request_ms: ms, budget, memory_ids: (data.memories ?? []).map((m: any) => m.id) });
    return String(data.context ?? "").trim();
  } catch (e) {
    box.audit("recall_failure", session, { type: e instanceof Error ? e.name : "error", request_ms: Math.round(performance.now() - started), retry_policy: "next_prompt" });
    return "";
  }
}

function capture(cred: Credential, box: Outbox, input: any, s: Settings) {
  const session = String(input.session_id ?? "");
  if (!session || typeof input.transcript_path !== "string") return [];
  const history = transcriptMessages(input.transcript_path);
  for (const m of history) box.enqueue(cred, session, m, s.owner_author_id ?? null);
  return history;
}

async function readStdin() {
  try { return JSON.parse(await Bun.stdin.text() || "{}"); } catch { return {}; }
}

export async function main(argv = process.argv.slice(2)) {
  const [mode, dataArg] = argv;
  if (mode === "headers") {
    // MCP headersHelper: the token comes from the private file, never from config or env.
    const cred = credential();
    process.stdout.write(JSON.stringify({ Authorization: `Bearer ${cred.token}`, "X-Atlas-Capture": "automatic" }));
    return;
  }
  const dir = dataArg && !dataArg.includes("${") ? dataArg : process.env.CLAUDE_PLUGIN_DATA || join(homedir(), ".claude", "plugins", "data", "atlas-memory");
  if (mode === "status") {
    const box = new Outbox(dir);
    console.log(JSON.stringify({ version: VERSION, credential_file: credentialPath(), credential_present: existsSync(credentialPath()), outbox: box.status() }, null, 2));
    box.close(); return;
  }
  if (!["prompt", "stop", "end"].includes(mode)) { console.error("usage: atlas.ts prompt|stop|end|headers|status [data-dir]"); return; }
  const input = await readStdin();
  if (!existsSync(credentialPath())) return; // Not configured on this host: stay silent.
  const cred = credential(), s = settings(), box = new Outbox(dir);
  try {
    const history = capture(cred, box, input, s);
    if (mode === "prompt") {
      const packet = await recall(cred, box, input, history, s);
      if (packet) process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: "UserPromptSubmit", additionalContext: packet } }));
    } else {
      await flush(cred, box, mode === "stop" ? 8000 : 6000);
      box.retain(Number(s.retention_days ?? 30));
    }
  } finally { box.close(); }
}

if (import.meta.main) {
  try { await main(); }
  catch (e) { console.error(`atlas-memory: ${e instanceof Error ? e.message : "error"}`); }
  process.exit(0);
}
