const at = '2026-01-01T00:00:00.000Z';
const kanbanNotice = '[kanban] Task t_a16c3e71 completed.\nTitle: Fix Atlas admission-review HTTP receipt serialization\nAssignee: @builder\n\nThis is an automatic task-status notification, not a request to decompose the task again.';
const backgroundNotice = '[IMPORTANT: Background process proc_7f42 completed normally (exit code 0).\nOutput:\nhistorical execution receipt]\n\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]';

function fixture() {
  const store = new Store(':memory:'), credential = store.bootstrap('Synthetic automatic notification boundary'), actor = store.authenticate(credential.token);
  const inputs: any[] = [], audits: any[] = [], embeds: any[] = [];
  const inference = {
    async curate(input: any) { inputs.push(structuredClone(input)); return { decisions: [{ kind: 'nothing' as const }] }; },
    async audit(input: any) { audits.push(structuredClone(input)); return { choice: 'durable_candidate', confidence: .9, probabilities: { durable_candidate: .9, other: .1 }, model: 'jev-double', elapsed_ms: 1, usage: { input_tokens: 1, output_tokens: 1 } }; },
    async embed(texts: string[]) { embeds.push([...texts]); return { vectors: texts.map(() => [1, 0]), model: 'communication-double' }; },
  };
  const memory = new Memory(store, inference), worker = new MemoryWorker(store, inference);
  memory.bind(actor, actor.id, 'default');
  const event = (event_id: string, extra: any = {}) => memory.event(actor, {
    client_id: 'communication', event_id, revision: 1, operation: 'upsert', agent_id: 'default', thread_id: event_id,
    role: 'user', author_id: 'alex', occurred_at: at, observed_at: now(), content: `Fictional communication ${event_id}`, metadata: {}, ...extra,
  });
  return { store, actor, credential, memory, worker, inputs, audits, embeds, event };
}

function legacySource(f: ReturnType<typeof fixture>, eventId: string, content: string, extra: any = {}) {
  const submitted = f.event(eventId, {
    thread_id: extra.thread_id ?? 'legacy-notifications',
    role: extra.role ?? 'inter_agent',
    author_id: extra.role === 'user' ? 'alex' : 'agent:default',
    content: 'Synthetic communication accepted before the automatic-notification boundary',
    metadata: {},
  });
  const metadata = extra.metadata ?? { boundary: 'generated_notification', notification_source: 'kanban-wake', display_kind: 'internal_notification' };
  f.store.run('UPDATE memory_events SET content=?,role=?,author_id=?,metadata_json=? WHERE event_id=?',
    content, extra.role ?? 'inter_agent', extra.author_id ?? 'native:notification:kanban-wake', JSON.stringify(metadata), eventId);
  return { job_id: submitted.job_id, source: f.store.one('SELECT * FROM memory_events WHERE event_id=?', eventId) };
}

function applyMemory(f: ReturnType<typeof fixture>, target: { job_id: string, source: any }, object: string, scope = 'agent:default', subject = 'Atlas automatic status') {
  const memoryId = f.worker.apply(target.source, {
    kind: 'episode' as const, scope, subject, predicate: 'reported', object,
    valid_from: at, valid_to: null, importance: 1, confidence: .9, evidence_event_ids: [target.source.event_id],
  }, [1, 0], 'communication-double', [scope]);
  f.store.run("UPDATE memory_jobs SET status='succeeded',completed_at=? WHERE id=?", now(), target.job_id);
  f.store.run("UPDATE memory_events SET status='processed',processed_at=? WHERE id=?", now(), target.source.id);
  return { ...target, memory: memoryId, object, scope };
}

function notificationMemory(f: ReturnType<typeof fixture>, eventId: string, object: string, extra: any = {}) {
  const source = legacySource(f, eventId, extra.content ?? kanbanNotice, extra);
  return applyMemory(f, source, object, extra.scope ?? 'agent:default', extra.subject ?? `Automatic task ${eventId}`);
}

function genuineMemory(f: ReturnType<typeof fixture>, eventId: string, object: string) {
  const submitted = f.event(eventId, { thread_id: 'current-requirement', role: 'user', author_id: 'alex', content: object });
  const source = f.store.one('SELECT * FROM memory_events WHERE event_id=?', eventId);
  return applyMemory(f, { job_id: submitted.job_id, source }, object, 'user:alex', 'Atlas durable communication');
}

const graph = (f: ReturnType<typeof fixture>, recorded_at = now(), include_history = false) => memoryGraph(f.memory, f.actor, {
  agent_id: 'default', query: 't_cb043bca', include_history, valid_at: at, recorded_at, limit: 100,
});

test('exact machine status and delivery notices are not admitted, while genuine task discussion remains eligible', async () => {
  const f = fixture();
  try {
    const notices = [
      ['kanban-status', kanbanNotice, { role: 'inter_agent', author_id: 'native:kanban:sid:S-1-5-21', metadata: { native_source: 'kanban', boundary: 'input' } }],
      ['discord-kanban-status', '[Alex] [kanban] Task t_801f3e17 completed.\nTitle: historical activation\n\nThis is an automatic task-status notification, not a request to decompose the task again.', { role: 'user', author_id: 'alex', metadata: { native_source: 'discord', boundary: 'input' } }],
      ['kanban-crashed', '[Alex] [kanban] Task t_6406e00d crashed (worker exited); dispatcher will retry.\nTitle: historical research', { role: 'inter_agent', author_id: 'native:kanban:sid:S-1-5-21', metadata: { native_source: 'kanban', boundary: 'input' } }],
      ['kanban-wake', '[kanban-wake] Task t_a16c3e71 completed.\nTitle: historical receipt', { role: 'inter_agent', author_id: 'native:notification:kanban-wake' }],
      ['background-completion', backgroundNotice, { role: 'user', author_id: 'native:user:unknown', metadata: { display_kind: 'internal_notification' } }],
      ['discord-background-completion', '[Alex] [IMPORTANT: Background process proc_8a2ca1250a2e completed normally (exit code 0).\nCommand: historical command]', { role: 'user', author_id: 'alex', metadata: { native_source: 'discord', boundary: 'input' } }],
      ['delivery-receipt', '[completion] Background process proc_7f42 result delivered to builder.', { role: 'inter_agent', author_id: 'native:notification:completion' }],
      ['folded-background', '[IMPORTANT: 3 background process results arrived while this session was busy. Treat them as one batch.]\n\nproc_a finished\nproc_b finished', { role: 'inter_agent', author_id: 'native:notification:completion', metadata: { boundary: 'generated_notification', notification_source: 'completion', display_kind: 'internal_notification' } }],
      ['internal-notification', '[INTERNAL NOTIFICATION — generated by gateway] automatic delivery acknowledgement', { role: 'inter_agent', author_id: 'native:notification:loop-tick' }],
    ] as const;
    for (const [eventId, content, extra] of notices)
      expect(() => f.event(eventId, { ...extra, content })).toThrow('Automatic status/delivery notification');
    expect(f.store.one('SELECT COUNT(*) AS n FROM memory_events').n).toBe(0);
    expect(f.store.one('SELECT COUNT(*) AS n FROM memory_jobs').n).toBe(0);
    expect(f.store.one('SELECT COUNT(*) AS n FROM memories').n).toBe(0);

    const genuine = [
      ['alex-task-outcome', { role: 'user', author_id: 'alex', content: 'Please remember that task t_a16c3e71 has a durable outcome Alex wants available next week.' }],
      ['alex-kanban-request', { role: 'user', author_id: 'alex', content: '[kanban] Please remember this task outcome matters to me.' }],
      ['agent-reasoning', { role: 'inter_agent', author_id: 'agent:overwatch', content: 'Builder to Overwatch: I think task t_a16c3e71 should exclude only machine receipts because genuine agent reasoning remains useful.', metadata: { boundary: 'delegated_result', status: 'completed' } }],
      ['alex-background-discussion', { role: 'user', author_id: 'alex', content: 'Background process completion is worth discussing: remember that Alex prefers concise status summaries.' }],
    ] as const;
    for (const [eventId, extra] of genuine) f.event(eventId, extra);
    for (let n = 0; n < genuine.length; n++) await f.worker.runOnce();
    expect(f.inputs.map((input: any) => input.event.event_id).sort()).toEqual(genuine.map(([id]) => id).sort());
    expect(f.audits).toHaveLength(genuine.length);
    expect(f.store.one("SELECT COUNT(*) AS n FROM memory_jobs WHERE status='succeeded'").n).toBe(genuine.length);
  } finally { f.store.close(); }
});

test('legacy queued notices are capture-only without JEV/Luna and cannot contaminate later provider context or reprocess', async () => {
  const f = fixture();
  try {
    const legacy = legacySource(f, 'legacy-background', backgroundNotice, {
      role: 'user', author_id: 'native:user:unknown', metadata: { display_kind: 'internal_notification', boundary: 'input' },
    });
    expect(await f.worker.runOnce()).toBe(true);
    expect(f.store.one('SELECT status FROM memory_jobs WHERE id=?', legacy.job_id).status).toBe('skipped');
    expect(f.store.one('SELECT status,content FROM memory_events WHERE id=?', legacy.source.id)).toEqual({ status: 'captured', content: backgroundNotice });
    expect(f.store.one('SELECT decision,model FROM memory_event_admissions WHERE job_id=?', legacy.job_id)).toEqual({ decision: 'noise', model: 'automatic_status_boundary' });
    expect(f.audits).toHaveLength(0); expect(f.inputs).toHaveLength(0); expect(f.embeds).toHaveLength(0);
    expect(f.store.one('SELECT COUNT(*) AS n FROM memories').n).toBe(0);
    expect(() => f.memory.reprocess(f.actor, 'default', legacy.job_id, 1, 'automatic_notification_owner_exclusion')).toThrow('Automatic status/delivery notification');

    f.event('genuine-after-legacy', { thread_id: 'legacy-notifications', role: 'inter_agent', author_id: 'agent:overwatch', content: 'Genuine reasoning about the notification boundary and why task discussion must remain eligible.' });
    await f.worker.runOnce();
    expect(f.audits).toHaveLength(1); expect(f.audits[0].previous).toEqual([]);
    expect(f.inputs).toHaveLength(1); expect(f.inputs[0].recent_events).toEqual([]); expect(f.inputs[0].candidates).toEqual([]);
    expect(JSON.stringify(f.audits[0])).not.toContain('historical execution receipt');
    expect(JSON.stringify(f.inputs[0])).not.toContain('historical execution receipt');
  } finally { f.store.close(); }
});

test('notification-only owner demotion preserves history and frees compact recall for the current relevant fact', async () => {
  const f = fixture();
  try {
    const relevant = genuineMemory(f, 'actual-current-requirement', 'Alex requires Atlas durable communication memory for task t_cb043bca to retain genuine reasoning and the current requirement, not automatic status notices.');
    const notices = Array.from({ length: 5 }, (_, index) => notificationMemory(f, `old-status-${index}`,
      `Automatic Kanban task t_cb043bca status report ${index}: old historical task outcome and delivery receipt, not Alex's current durable communication requirement.`));
    const tables = ['memory_events', 'memory_jobs', 'memories', 'memory_supports', 'memory_versions'];
    const snapshots = Object.fromEntries(tables.map(table => [table, f.store.all(`SELECT * FROM ${table} ORDER BY rowid`)]));
    const before = now(); await Bun.sleep(3);
    const query = 'What is the current Atlas durable communication requirement for task t_cb043bca?';
    const crowded = await f.memory.recall(f.actor, { agent_id: 'default', thread_id: 'fresh-notification-check', query, recent_context: [], token_budget: 320 });
    expect(crowded.memories.some((m: any) => notices.some(target => target.memory === m.id))).toBe(true);
    // Focused selection may retain the relevant fact even before demotion; demotion must remove
    // notification noise without sacrificing that fact or rewriting durable history.
    expect(crowded.memories.some((m: any) => m.id === relevant.memory)).toBe(true);
    expect(graph(f, before).edges.some((edge: any) => notices.some(target => target.memory === edge.id))).toBe(true);

    const modelCallsBefore = f.audits.length + f.inputs.length + f.embeds.length;
    for (const target of notices) {
      const review = f.memory.reviewAdmission(f.actor, 'default', target.job_id, target.memory, 1, 'automatic_notification_owner_exclusion');
      expect(review).toMatchObject({ memory_id: target.memory, decision: 'session_context', model: 'owner_directive', confidence: 1, demoted: true });
    }
    expect(f.audits.length + f.inputs.length + f.embeds.length).toBe(modelCallsBefore);
    expect(f.store.one("SELECT COUNT(*) AS n FROM memory_admission_demotions WHERE reason_code='automatic_notification_owner_exclusion'").n).toBe(5);
    expect(graph(f).edges.some((edge: any) => notices.some(target => target.memory === edge.id))).toBe(false);
    const historical = graph(f, before, true);
    expect(notices.every(target => historical.edges.some((edge: any) => edge.id === target.memory))).toBe(true);
    for (const table of tables) expect(f.store.all(`SELECT * FROM ${table} ORDER BY rowid`)).toEqual(snapshots[table]);

    const recall = await f.memory.recall(f.actor, { agent_id: 'default', thread_id: 'fresh-notification-check', query, recent_context: [], token_budget: 320 });
    expect(recall.memories.map((m: any) => m.id)).toContain(relevant.memory);
    expect(recall.memories.some((m: any) => notices.some(target => target.memory === m.id))).toBe(false);
    expect(recall.context).toContain('genuine reasoning and the current requirement');
    expect(recall.freshness.pending_included).toBe(0); expect(recall.pending_events).toEqual([]);
  } finally { f.store.close(); }
});

test('automatic-notification demotion enforces exact source, revision, direct-support, notification-only and grant fences without model calls', () => {
  const f = fixture();
  try {
    const target = notificationMemory(f, 'fence-target', 'Synthetic automatic notification-only memory t_cb043bca');
    const other = notificationMemory(f, 'fence-other', 'Other automatic notification-only memory t_cb043bca');
    const genuine = genuineMemory(f, 'fence-genuine', 'Genuine Alex task outcome t_cb043bca');
    expect(() => f.memory.reviewAdmission(f.actor, 'default', target.job_id, target.memory, 2, 'automatic_notification_owner_exclusion')).toThrow('Memory event revision changed');
    expect(() => f.memory.reviewAdmission(f.actor, 'default', target.job_id, other.memory, 1, 'automatic_notification_owner_exclusion')).toThrow('Memory with direct source support');
    expect(() => f.memory.reviewAdmission(f.actor, 'default', genuine.job_id, genuine.memory, 1, 'automatic_notification_owner_exclusion')).toThrow('not an automatic status/delivery notification');

    const genuineSupport = f.event('mixed-genuine-support', { thread_id: 'legacy-notifications', role: 'user', author_id: 'alex', content: target.object });
    const genuineSource = f.store.one('SELECT * FROM memory_events WHERE event_id=?', 'mixed-genuine-support');
    expect(f.worker.apply(genuineSource, {
      kind: 'episode' as const, scope: target.scope, subject: `Automatic task fence-target`, predicate: 'reported', object: target.object,
      valid_from: at, valid_to: null, importance: 1, confidence: .9, evidence_event_ids: ['mixed-genuine-support'],
    }, [1, 0], 'communication-double', [target.scope])).toBe(target.memory);
    expect(() => f.memory.reviewAdmission(f.actor, 'default', target.job_id, target.memory, 1, 'automatic_notification_owner_exclusion')).toThrow('notification-only direct support');
    f.store.run('DELETE FROM memory_supports WHERE event_pk=? AND memory_id=?', genuineSource.id, target.memory);

    f.store.run("DELETE FROM memory_grants WHERE principal_id=? AND scope='agent:default' AND action='write'", f.actor.id);
    expect(() => f.memory.reviewAdmission(f.actor, 'default', target.job_id, target.memory, 1, 'automatic_notification_owner_exclusion')).toThrow('grant required');
    f.store.run("INSERT INTO memory_grants VALUES (?,?,?)", f.actor.id, 'agent:default', 'write');

    f.store.run('UPDATE memory_events SET job_id=? WHERE id=?', other.job_id, target.source.id);
    expect(() => f.memory.reviewAdmission(f.actor, 'default', target.job_id, target.memory, 1, 'automatic_notification_owner_exclusion')).toThrow('Current source job not found');
    f.store.run('UPDATE memory_events SET job_id=? WHERE id=?', target.job_id, target.source.id);
    expect(f.inputs).toHaveLength(0); expect(f.audits).toHaveLength(0); expect(f.embeds).toHaveLength(0);
    expect(f.store.one('SELECT COUNT(*) AS n FROM memory_admission_reviews').n).toBe(0);
    expect(f.store.one('SELECT COUNT(*) AS n FROM memory_admission_demotions').n).toBe(0);
    expect(() => f.memory.reprocess(f.actor, 'default', target.job_id, 1, 'automatic_notification_owner_exclusion')).toThrow('Automatic status/delivery notification');
  } finally { f.store.close(); }
});
